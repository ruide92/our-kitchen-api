#!/usr/bin/env node
// Generate docs/PRODUCT_SURFACE_MATRIX.md from governance/product-surfaces.json
// The Markdown is a DERIVED human-readable view. JSON is the single authority.
// Usage: node scripts/generate-product-surface-matrix.js [--check]
const fs = require('node:fs');
const path = require('node:path');

const ROOT = process.cwd();
const REGISTRY_PATH = path.join(ROOT, 'governance', 'product-surfaces.json');
const MATRIX_PATH = path.join(ROOT, 'docs', 'PRODUCT_SURFACE_MATRIX.md');
const checkMode = process.argv.includes('--check');

const STATUS_ORDER = ['REAL', 'PARTIAL', 'BROKEN', 'KNOWN_BROKEN', 'PLANNED_DISABLED', 'HIDDEN'];

function generateMarkdown(surfaces) {
  const lines = [];
  lines.push('# Product Surface Matrix');
  lines.push('');
  lines.push('> **DERIVED / HUMAN-READABLE VIEW.** Do not edit this file manually.');
  lines.push('> Single source of truth: `governance/product-surfaces.json`.');
  lines.push('> Regenerate with: `node scripts/generate-product-surface-matrix.js`');
  lines.push('> Sync check: `node scripts/generate-product-surface-matrix.js --check`');
  lines.push('');

  // Summary by status
  const byStatus = {};
  for (const s of surfaces) {
    byStatus[s.status] = (byStatus[s.status] || 0) + 1;
  }
  lines.push('## Summary');
  lines.push('');
  lines.push('| Status | Count |');
  lines.push('|---|---|');
  for (const st of STATUS_ORDER) {
    if (byStatus[st]) lines.push(`| ${st} | ${byStatus[st]} |`);
  }
  lines.push(`| **Total** | **${surfaces.length}** |`);
  lines.push('');

  // Group by page
  const byPage = {};
  for (const s of surfaces) {
    const p = s.page || '(global)';
    if (!byPage[p]) byPage[p] = [];
    byPage[p].push(s);
  }

  lines.push('## Surfaces');
  lines.push('');
  for (const page of Object.keys(byPage).sort()) {
    lines.push(`### ${page}`);
    lines.push('');
    lines.push('| ID | Kind | Handler/Label | Status | Final |');
    lines.push('|---|---|---|---|---|');
    for (const s of byPage[page].sort((a, b) => a.id.localeCompare(b.id))) {
      const handler = s.handler || s.label || s.action || s.surface_id || s.url || '-';
      const handlerEsc = String(handler).replace(/\|/g, '\\|');
      lines.push(`| ${s.id} | ${s.kind} | ${handlerEsc} | ${s.status} | ${s.final} |`);
    }
    lines.push('');
  }

  return lines.join('\n') + '\n';
}

function main() {
  const data = JSON.parse(fs.readFileSync(REGISTRY_PATH, 'utf8'));
  const surfaces = data.surfaces || [];
  const generated = generateMarkdown(surfaces);

  if (checkMode) {
    if (!fs.existsSync(MATRIX_PATH)) {
      console.error('FAIL: docs/PRODUCT_SURFACE_MATRIX.md does not exist');
      process.exit(1);
    }
    const current = fs.readFileSync(MATRIX_PATH, 'utf8');
    if (current !== generated) {
      console.error('FAIL: docs/PRODUCT_SURFACE_MATRIX.md is out of sync with governance/product-surfaces.json');
      console.error('Run: node scripts/generate-product-surface-matrix.js');
      process.exit(1);
    }
    console.log('PASS: PRODUCT_SURFACE_MATRIX.md is in sync with product-surfaces.json');
    process.exit(0);
  }

  fs.writeFileSync(MATRIX_PATH, generated, 'utf8');
  console.log(`Generated ${MATRIX_PATH} (${surfaces.length} surfaces)`);
}

main();
